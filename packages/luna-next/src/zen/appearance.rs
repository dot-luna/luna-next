//! Render Zen's profile styles and preferences from Luna's resolved theme.

use std::{fmt::Write as _, fs, path::Path};

use serde_json::{Value, json};

use crate::{Error, Result, io_error};

// Match Gecko's language groups without replacing its math fonts or fallback lists.
const FONT_GROUPS: &[&str] = &[
    "ar",
    "el",
    "he",
    "ja",
    "ko",
    "th",
    "x-armn",
    "x-beng",
    "x-cans",
    "x-cyrillic",
    "x-devanagari",
    "x-ethi",
    "x-geor",
    "x-gujr",
    "x-guru",
    "x-khmr",
    "x-knda",
    "x-mlym",
    "x-orya",
    "x-sinh",
    "x-tamil",
    "x-telu",
    "x-tibt",
    "x-unicode",
    "x-western",
    "zh-CN",
    "zh-HK",
    "zh-TW",
];

pub(super) struct Rendered {
    pub(super) user_js: String,
    pub(super) user_chrome: String,
    pub(super) user_content: String,
}

/// Render owned profile files without writing them or starting Zen. The caller
/// supplies a resolved, schema-validated theme and publishes the generated files.
/// Native colors/fonts stay within browser UI; websites retain their own fonts
/// and colors, with a corner override only when Luna's rounding is zero.
pub(super) fn render(config_dir: &Path, theme: &Value) -> Result<Rendered> {
    let ui = text(&theme["fonts"]["ui"], "fonts.ui")?;
    let mono = text(&theme["fonts"]["mono"], "fonts.mono")?;
    let rounding = theme["appearance"]["rounding"].as_u64().ok_or_else(|| {
        Error::Message("Resolved Luna theme is missing 'appearance.rounding'".into())
    })?;
    let square = rounding == 0;
    let square_chrome = if square {
        read(config_dir, "square-chrome.css")?
    } else {
        String::new()
    };
    let template = read(config_dir, "userChrome.css")?;
    let user_chrome = render_chrome(&template, theme, &css_string(ui), &square_chrome)?;
    let user_content = if square {
        read(config_dir, "square-content.css")?
    } else {
        "/* Luna leaves website corner styles unchanged when rounding is enabled. */\n".into()
    };

    let mut user_js = String::from("// Generated by Luna; rerun luna conf zen to refresh.\n");
    for (name, value) in [
        (
            "toolkit.legacyUserProfileCustomizations.stylesheets",
            json!(true),
        ),
        ("browser.display.use_document_fonts", json!(1)),
        // Only the profile extension scope may activate sideloaded signed XPIs.
        ("extensions.autoDisableScopes", json!(14)),
        ("extensions.startupScanScopes", json!(1)),
        ("xpinstall.signatures.required", json!(true)),
        // -1 restores Zen's native radius after a previously square Luna theme.
        (
            "zen.theme.border-radius",
            json!(if square { 0 } else { -1 }),
        ),
    ] {
        preference(&mut user_js, name, value)?;
    }
    for group in FONT_GROUPS {
        preference(
            &mut user_js,
            &format!("font.default.{group}"),
            json!("sans-serif"),
        )?;
        for (family, font) in [("serif", ui), ("sans-serif", ui), ("monospace", mono)] {
            preference(
                &mut user_js,
                &format!("font.name.{family}.{group}"),
                json!(font),
            )?;
        }
    }

    Ok(Rendered {
        user_js,
        user_chrome,
        user_content,
    })
}

fn preference(output: &mut String, name: &str, value: Value) -> Result<()> {
    writeln!(
        output,
        "user_pref({}, {});",
        serde_json::to_string(name)?,
        serde_json::to_string(&value)?
    )
    .unwrap();
    Ok(())
}

fn render_chrome(template: &str, theme: &Value, ui: &str, square: &str) -> Result<String> {
    let mut output = String::with_capacity(template.len());
    let mut remaining = template;
    // Resolve the source once so a font containing template delimiters stays literal.
    while let Some((before, after)) = remaining.split_once("{{") {
        output.push_str(before);
        let (token, after) = after.split_once("}}").ok_or_else(|| {
            Error::Message("Zen userChrome.css contains an unclosed theme token".into())
        })?;
        match token {
            "ui_font" => output.push_str(ui),
            "square_chrome" => output.push_str(square),
            _ if token.starts_with("colors.") => {
                output.push_str(text(&theme["colors"][&token[7..]], token)?);
            }
            _ => return Err(Error::Message(format!("Unknown Zen theme token '{token}'"))),
        }
        remaining = after;
    }
    output.push_str(remaining);
    Ok(output)
}

fn text<'a>(value: &'a Value, name: &str) -> Result<&'a str> {
    value
        .as_str()
        .ok_or_else(|| Error::Message(format!("Resolved Luna theme is missing '{name}'")))
}

fn read(directory: &Path, name: &str) -> Result<String> {
    let path = directory.join(name);
    fs::read_to_string(&path)
        .map_err(|error| io_error("read Zen appearance template", &path, error))
}

fn css_string(value: &str) -> String {
    let mut escaped = String::from("\"");
    for character in value.chars() {
        match character {
            '\\' | '"' => {
                escaped.push('\\');
                escaped.push(character);
            }
            '\0' => escaped.push('\u{fffd}'),
            character if character.is_control() => {
                write!(escaped, "\\{:x} ", character as u32).unwrap();
            }
            _ => escaped.push(character),
        }
    }
    escaped.push('"');
    escaped
}

