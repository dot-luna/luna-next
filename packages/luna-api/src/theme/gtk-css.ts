import type { ResolvedTheme, ThemeMode } from "./types.ts";

/** GTK3 widget structure comes from GTK; resolved Luna colors stay fixed across mode overrides. */
export function gtkCss(theme: ResolvedTheme, mode: ThemeMode): string {
  const c = theme.colors;
  const named = {
    theme_bg_color: c.background,
    theme_fg_color: c.foreground,
    theme_base_color: c.dark_background,
    theme_text_color: c.foreground,
    theme_selected_bg_color: c.selection,
    theme_selected_fg_color: c.selection_foreground,
    theme_unfocused_bg_color: c.background,
    theme_unfocused_fg_color: c.foreground,
    theme_unfocused_base_color: c.dark_background,
    theme_unfocused_text_color: c.foreground,
    theme_unfocused_selected_bg_color: c.selection,
    theme_unfocused_selected_fg_color: c.selection_foreground,
    insensitive_bg_color: c.background,
    insensitive_fg_color: c.dark_foreground,
    insensitive_base_color: c.dark_background,
    borders: c.muted,
    unfocused_borders: c.muted,
    warning_color: c.warning,
    error_color: c.error,
    success_color: c.success,
  };
  // A quoted family keeps punctuation in validated font names from becoming CSS syntax.
  const uiFont = theme.fonts.ui.replace(/[\\"]/gu, "\\$&");
  const monoFont = theme.fonts.mono.replace(/[\\"]/gu, "\\$&");
  const variant = mode === "dark" ? "-dark" : "";
  return `/* Generated by Luna. */
@import url("resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained${variant}.css");
${Object.entries(named)
  .map(([name, color]) => `@define-color ${name} ${color};`)
  .join("\n")}

/* Adwaita contains literal colors, so named colors alone cannot recolor its widgets. */
* {
  font-family: "${uiFont}";
  outline-color: ${c.accent};
  -gtk-icon-palette: error @error_color, warning @warning_color, success @success_color;
}
.monospace, .monospace * { font-family: "${monoFont}"; }
/* Keep GTK's more specific grouped-control and circular-control corner rules. */
button, entry, menuitem, modelbutton.flat, .menuitem.button.flat,
menu, .menu, .context-menu, .csd menu, .csd .menu, .csd .context-menu,
popover.background, .csd popover.background, tooltip, tooltip.background {
  border-radius: ${theme.appearance.rounding}px;
}
window, .background, window:backdrop, .background:backdrop {
  color: @theme_fg_color;
  background-color: @theme_bg_color;
}
menu, .menu, .context-menu, menubar, popover.background,
headerbar, .titlebar, toolbar, .toolbar, statusbar, notebook > header,
menu:backdrop, menubar:backdrop, popover.background:backdrop, headerbar:backdrop {
  color: @theme_fg_color;
  background-color: @theme_base_color;
  background-image: none;
  border-color: @borders;
  box-shadow: none;
  text-shadow: none;
}
menuitem, menu menuitem, .menu menuitem, .context-menu menuitem, menubar > menuitem,
menu menuitem:backdrop, .menu menuitem:backdrop, .context-menu menuitem:backdrop {
  color: @theme_fg_color;
  background-color: transparent;
  background-image: none;
}
menuitem:hover, menu menuitem:hover, .menu menuitem:hover, .context-menu menuitem:hover,
menubar > menuitem:hover, menu menuitem:hover:backdrop,
.menu menuitem:hover:backdrop, .context-menu menuitem:hover:backdrop {
  color: @theme_selected_fg_color;
  background-color: @theme_selected_bg_color;
}
button, button:backdrop, switch slider, switch:hover slider, switch:backdrop slider,
treeview.view header button, treeview.view header button:backdrop {
  color: @theme_fg_color;
  background-color: ${c.lighter_background};
  background-image: none;
  border-color: @borders;
  box-shadow: none;
  text-shadow: none;
  -gtk-icon-shadow: none;
}
button:hover, button:hover:backdrop, treeview.view header button:hover {
  color: @theme_selected_fg_color;
  background-color: ${c.selection};
  background-image: none;
  border-color: @borders;
}
button:active, button:checked, button:active:backdrop, button:checked:backdrop,
button.suggested-action, button.suggested-action:hover, button.suggested-action:backdrop {
  color: ${c.accent_foreground};
  background-color: ${c.accent};
  background-image: none;
  border-color: ${c.accent};
  text-shadow: none;
}
button.destructive-action, button.destructive-action:hover, button.destructive-action:backdrop {
  color: ${c.error_foreground};
  background-color: ${c.error};
  background-image: none;
  border-color: ${c.error};
  text-shadow: none;
}
entry, entry:backdrop, spinbutton:not(.vertical), spinbutton:not(.vertical):backdrop,
textview, textview text, textview text:backdrop, treeview.view, treeview.view:backdrop,
iconview.view, .view, list, list:backdrop, row, row:backdrop {
  color: @theme_text_color;
  background-color: @theme_base_color;
  background-image: none;
  border-color: @borders;
  box-shadow: none;
}
entry:focus, spinbutton:not(.vertical):focus, treeview entry:focus,
treeview entry:focus:dir(ltr), treeview entry:focus:dir(rtl) {
  border-color: ${c.accent};
  box-shadow: inset 0 0 0 1px ${c.accent};
}
button:focus, checkbutton:focus, radiobutton:focus, switch:focus, scale:focus {
  outline-color: ${c.accent};
}
entry.error, entry.error:focus { border-color: ${c.error}; }
entry.warning, entry.warning:focus { border-color: ${c.warning}; }
selection, selection:focus, textview text selection, textview text selection:focus,
treeview.view:selected, treeview.view:selected:focus, treeview.view:selected:backdrop,
iconview.view:selected, row:selected, row:selected:backdrop {
  color: @theme_selected_fg_color;
  background-color: @theme_selected_bg_color;
}
check:not(:checked):not(:indeterminate), radio:not(:checked):not(:indeterminate),
switch, switch:backdrop, scale trough, progressbar trough, scrollbar trough {
  color: @theme_fg_color;
  background-color: @theme_base_color;
  background-image: none;
  border-color: @borders;
  box-shadow: none;
  text-shadow: none;
}
check:checked:not(:disabled), check:indeterminate:not(:disabled),
radio:checked:not(:disabled), radio:indeterminate:not(:disabled),
check:checked:backdrop:not(:disabled), radio:checked:backdrop:not(:disabled),
switch:checked:not(:disabled), switch:checked:backdrop:not(:disabled),
scale highlight, progressbar progress {
  color: ${c.accent_foreground};
  background-color: ${c.accent};
  background-image: none;
  border-color: ${c.accent};
  box-shadow: none;
  text-shadow: none;
}
scale slider, scale slider:hover, scale slider:backdrop,
scrollbar slider, scrollbar slider:hover, scrollbar slider:backdrop {
  background-color: ${c.muted};
  background-image: none;
  border-color: @borders;
  box-shadow: none;
}
separator { background-color: @borders; }
frame > border, scrolledwindow > overshoot, notebook > header { border-color: @borders; }
notebook > header > tabs > tab:checked { box-shadow: inset 0 -2px ${c.accent}; }
label:link, button:link { color: ${c.link}; }
label:visited, button:visited { color: ${c.link_emphasis}; }
tooltip, tooltip.background { color: @theme_fg_color; background-color: ${c.darker_background}; }
*:disabled,
entry:disabled, entry:disabled:backdrop, treeview.view:disabled, treeview.view:disabled:backdrop,
menu menuitem:disabled, menu menuitem:disabled:backdrop,
.menu menuitem:disabled, .menu menuitem:disabled:backdrop,
.context-menu menuitem:disabled, .context-menu menuitem:disabled:backdrop {
  color: @insensitive_fg_color;
  text-shadow: none;
  -gtk-icon-shadow: none;
}
button:disabled, button:disabled:backdrop, entry:disabled, entry:disabled:backdrop,
button:disabled:checked, button:disabled:checked:backdrop,
button.suggested-action:disabled, button.suggested-action:disabled:backdrop,
button.suggested-action:disabled:checked, button.suggested-action:disabled:checked:backdrop,
button.destructive-action:disabled, button.destructive-action:disabled:backdrop,
button.destructive-action:disabled:checked, button.destructive-action:disabled:checked:backdrop,
check:disabled, check:disabled:backdrop, check:disabled:checked, check:disabled:checked:backdrop,
check:disabled:not(:checked):not(:indeterminate),
check:disabled:indeterminate, check:disabled:indeterminate:backdrop,
radio:disabled, radio:disabled:backdrop, radio:disabled:checked, radio:disabled:checked:backdrop,
radio:disabled:not(:checked):not(:indeterminate),
radio:disabled:indeterminate, radio:disabled:indeterminate:backdrop,
switch:disabled, switch:disabled:backdrop, switch:disabled slider, switch:disabled:backdrop slider {
  color: @insensitive_fg_color;
  background-color: @insensitive_bg_color;
  background-image: none;
  border-color: @borders;
  box-shadow: none;
}
`;
}
