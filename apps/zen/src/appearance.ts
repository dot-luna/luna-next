export type Theme = {
  colors: Record<string, string>;
  fonts: { ui: string; mono: string };
  appearance: { rounding: number };
};

const config = new URL("../config/", import.meta.url);

/** Render browser UI and internal-page styles without changing website colors or shapes. */
export async function renderAppearance(
  theme: Theme,
  preferences: Record<string, string | number | boolean>,
): Promise<string[]> {
  const square = theme.appearance.rounding === 0;
  const tokens = await Bun.file(new URL("theme-tokens.css", config)).text();
  const chromeTemplate = (await Bun.file(new URL("userChrome.css", config)).text()).replace(
    "{{theme_tokens}}",
    tokens,
  );
  const contentTemplate = (await Bun.file(new URL("userContent.css", config)).text()).replace(
    "{{theme_tokens}}",
    tokens,
  );
  const squareChrome = square ? await Bun.file(new URL("square-chrome.css", config)).text() : "";
  function render(template: string): string {
    // Replace only original tokens; delimiters inside font names stay literal.
    return template.replace(/\{\{([^{}]+)\}\}/gu, (_match, token: string) => {
      const value =
        token === "ui_font"
          ? JSON.stringify(theme.fonts.ui)
          : token === "square_chrome"
            ? squareChrome
            : token.startsWith("colors.")
              ? theme.colors[token.slice(7)]
              : undefined;
      if (typeof value !== "string")
        throw new Error("Unknown or missing Zen theme token: " + token);
      return value;
    });
  }
  const chrome = render(chromeTemplate);
  const content = render(contentTemplate);
  const values = { ...preferences, "zen.theme.border-radius": square ? 0 : -1 };
  const groups = [
    "ar",
    "el",
    "he",
    "ja",
    "ko",
    "th",
    "x-armn",
    "x-beng",
    "x-cans",
    "x-cyrillic",
    "x-devanagari",
    "x-ethi",
    "x-geor",
    "x-gujr",
    "x-guru",
    "x-khmr",
    "x-knda",
    "x-mlym",
    "x-orya",
    "x-sinh",
    "x-tamil",
    "x-telu",
    "x-tibt",
    "x-unicode",
    "x-western",
    "zh-CN",
    "zh-HK",
    "zh-TW",
  ];
  let user = "// Generated by Luna; rerun Zen's setup-profile.ts hook to refresh.\n";
  const preference = (name: string, value: string | number | boolean) => {
    user += "user_pref(" + JSON.stringify(name) + ", " + JSON.stringify(value) + ");\n";
  };
  for (const [name, value] of Object.entries(values)) preference(name, value);
  for (const group of groups) {
    preference("font.default." + group, "sans-serif");
    for (const [family, font] of [
      ["serif", theme.fonts.ui],
      ["sans-serif", theme.fonts.ui],
      ["monospace", theme.fonts.mono],
    ]) {
      preference("font.name." + family + "." + group, font);
    }
  }
  return [user, chrome, content];
}
