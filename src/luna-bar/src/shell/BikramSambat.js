function lastYear() { return FIRST_YEAR + MONTHS.length - 1; }

/** Days in a BS month (1-12), or 0 outside the table. */
function daysInMonth(year, month) {
    const row = MONTHS[year - FIRST_YEAR];
    return row ? row[month - 1] : 0;
}

/** Convert a local AD date to {year, month, day}; month is 1-12. Null outside the table. */
function fromAd(date) {
    let days = Math.round((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - EPOCH) / DAY);
    if (days < 0) return null;
    for (let y = 0; y < MONTHS.length; y++) {
        for (let m = 0; m < 12; m++) {
            if (days < MONTHS[y][m]) return { year: FIRST_YEAR + y, month: m + 1, day: days + 1 };
            days -= MONTHS[y][m];
        }
    }
    return null;
}

/** Convert a BS date to a local AD Date at midnight. Null outside the table. */
function toAd(year, month, day) {
    const index = year - FIRST_YEAR;
    if (index < 0 || index >= MONTHS.length || month < 1 || month > 12 || day < 1 || day > MONTHS[index][month - 1])
        return null;
    let days = day - 1;
    for (let y = 0; y < index; y++) for (let m = 0; m < 12; m++) days += MONTHS[y][m];
    for (let m = 0; m < month - 1; m++) days += MONTHS[index][m];
    const utc = new Date(EPOCH + days * DAY);
    return new Date(utc.getUTCFullYear(), utc.getUTCMonth(), utc.getUTCDate());
}
